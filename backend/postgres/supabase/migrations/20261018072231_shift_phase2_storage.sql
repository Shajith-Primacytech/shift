-- Phase 2 LOCAL development schema. Not approved for hosted application.
-- Roles/extension are explicitly provisioned by the guarded local fixture runner.
CREATE SCHEMA shift_private AUTHORIZATION shift_owner;
SET LOCAL ROLE shift_owner;
SET LOCAL search_path TO shift_private, extensions, pg_catalog;
REVOKE ALL ON SCHEMA shift_private FROM PUBLIC;
CREATE TABLE schema_migrations (version text PRIMARY KEY, checksum text NOT NULL, applied_at timestamptz NOT NULL DEFAULT clock_timestamp());
CREATE TABLE users (id text COLLATE "C" PRIMARY KEY, username text COLLATE "C" UNIQUE NOT NULL, name text COLLATE "C" NOT NULL, role text COLLATE "C" NOT NULL CHECK(role IN ('technician','supervisor')), password_hash text COLLATE "C" NOT NULL, created_at text COLLATE "C" NOT NULL);
CREATE TABLE sessions (token_hash text COLLATE "C" PRIMARY KEY, user_id text COLLATE "C" NOT NULL REFERENCES users(id), expires_at bigint NOT NULL);
CREATE TABLE login_attempts (key text COLLATE "C" NOT NULL, attempted_at bigint NOT NULL);
CREATE INDEX login_attempt_time ON login_attempts(key, attempted_at);
CREATE TABLE machines (id text COLLATE "C" PRIMARY KEY, data jsonb NOT NULL);
CREATE TABLE knowledge_records (id text COLLATE "C" PRIMARY KEY, owner_id text COLLATE "C" REFERENCES users(id), created_at text COLLATE "C" NOT NULL);
CREATE TABLE knowledge_versions (id text COLLATE "C" PRIMARY KEY, record_id text COLLATE "C" NOT NULL REFERENCES knowledge_records(id), revision integer NOT NULL, machine_id text COLLATE "C" NOT NULL REFERENCES machines(id), title text COLLATE "C" NOT NULL, symptom text COLLATE "C" NOT NULL, content text COLLATE "C" NOT NULL, kind text COLLATE "C" NOT NULL, author text COLLATE "C" NOT NULL, submitted_by text COLLATE "C" REFERENCES users(id), problem text COLLATE "C" NOT NULL DEFAULT '', root_cause text COLLATE "C" NOT NULL DEFAULT '', resolution text COLLATE "C" NOT NULL DEFAULT '', safety_notes text COLLATE "C" NOT NULL DEFAULT '', status text COLLATE "C" NOT NULL CHECK(status IN ('Pending','Approved','Rejected','Revoked')), created_at text COLLATE "C" NOT NULL, UNIQUE(record_id,revision));
CREATE TABLE review_events (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, version_id text COLLATE "C" NOT NULL REFERENCES knowledge_versions(id), reviewer_id text COLLATE "C" REFERENCES users(id), reviewer_name text COLLATE "C" NOT NULL, previous_status text COLLATE "C" NOT NULL, decision text COLLATE "C" NOT NULL, note text COLLATE "C" NOT NULL, created_at text COLLATE "C" NOT NULL);
CREATE TABLE source_documents (id text COLLATE "C" PRIMARY KEY, version_id text COLLATE "C" NOT NULL REFERENCES knowledge_versions(id), name text COLLATE "C" NOT NULL, media_type text COLLATE "C" NOT NULL, size bigint NOT NULL, sha256 text COLLATE "C" NOT NULL, data bytea NOT NULL, created_at text COLLATE "C" NOT NULL);
CREATE TABLE knowledge_chunks (id text COLLATE "C" PRIMARY KEY, version_id text COLLATE "C" NOT NULL REFERENCES knowledge_versions(id), document_id text COLLATE "C" REFERENCES source_documents(id), position integer NOT NULL, page integer, section text COLLATE "C", content text COLLATE "C" NOT NULL, content_hash text COLLATE "C" NOT NULL, search_vector tsvector GENERATED ALWAYS AS (to_tsvector('pg_catalog.simple'::regconfig, content)) STORED);
CREATE TABLE conversations (id text COLLATE "C" PRIMARY KEY, owner_id text COLLATE "C" NOT NULL REFERENCES users(id), machine_id text COLLATE "C" NOT NULL REFERENCES machines(id), created_at text COLLATE "C" NOT NULL);
CREATE TABLE conversation_messages (id text COLLATE "C" PRIMARY KEY, conversation_id text COLLATE "C" NOT NULL REFERENCES conversations(id), role text COLLATE "C" NOT NULL CHECK(role IN ('user','assistant')), content text COLLATE "C" NOT NULL, response_mode text COLLATE "C" NOT NULL, created_at text COLLATE "C" NOT NULL);
CREATE INDEX versions_status ON knowledge_versions(status,machine_id);
CREATE TABLE rag_generations (version_id text COLLATE "C" PRIMARY KEY REFERENCES knowledge_versions(id), fingerprint text COLLATE "C" NOT NULL, embedding_key text COLLATE "C" NOT NULL);
CREATE TABLE chunk_embeddings (chunk_id text COLLATE "C" PRIMARY KEY REFERENCES knowledge_chunks(id) ON DELETE CASCADE, embedding_key text COLLATE "C" NOT NULL, vector extensions.vector(384) NOT NULL);
CREATE TABLE capture_ai_runs (id text COLLATE "C" PRIMARY KEY, owner_id text COLLATE "C" NOT NULL REFERENCES users(id), original_submission jsonb NOT NULL, proposal jsonb, execution jsonb NOT NULL, created_at text COLLATE "C" NOT NULL, version_id text COLLATE "C" UNIQUE REFERENCES knowledge_versions(id), reviewed_structure jsonb);
CREATE INDEX capture_ai_owner_time ON capture_ai_runs(owner_id,created_at);
CREATE INDEX sessions_expiry ON sessions(expires_at);
CREATE INDEX sessions_user ON sessions(user_id);
CREATE INDEX attempts_expiry ON login_attempts(attempted_at);
CREATE INDEX records_owner ON knowledge_records(owner_id);
CREATE INDEX review_version_order ON review_events(version_id,id DESC);
CREATE INDEX documents_version ON source_documents(version_id);
CREATE INDEX chunks_version ON knowledge_chunks(version_id);
CREATE INDEX chunks_document ON knowledge_chunks(document_id);
CREATE INDEX chunks_search ON knowledge_chunks USING gin(search_vector);
